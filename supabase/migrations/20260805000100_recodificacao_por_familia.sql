-- Recodificação do catálogo por família, 05/08/2026.
--
-- O catálogo tinha 4 categorias institucionais (PC, CC, AC, KC) — e 216 dos
-- 324 produtos (dois terços) caíam todos em "CC". Uma vendedora vendo
-- "CC-0185" sabia só que era um campo; campo é quase tudo. O código não
-- informava nada de útil justamente onde havia mais produto.
--
-- Definido com o cliente: a primeira letra passa a ser a LINHA do produto, a
-- segunda a FAMÍLIA dentro dela — a mesma regra que "KC = Kit Cirúrgico" já
-- seguia, agora aplicada ao catálogo inteiro. E o hífen sai: só duas letras e
-- quatro dígitos, sem separador.
--
--   C_ Campos:        CS Simples · CM de Mesa · CF com Fenestra · CA com Adesivo
--                      CT Catarata · CL Lasik · CD Steri Drape · CG Geral (sobra)
--   P_ Paramentação:   PA Avental · PJ Conjunto · PB Bota · PP Perneira
--   A_ Acessórios:     AC Compressa · AS Saco · AB Bag · AO Oclusor
--   K_ Kits:           KC Kit Cirúrgico
--
-- Nenhum código antigo é reciclado com sentido novo — CC e PC (que hoje
-- significam "campo" e "paramentação" de forma genérica) são aposentados, não
-- reaproveitados, para que o mesmo texto nunca aponte para produtos diferentes
-- conforme a data. A exceção é AC: confirmado com o cliente que os códigos
-- antigos de Acessórios nunca circularam em nota ou pedido real (o sistema tem
-- ZERO pedidos até esta migração), então AC pode ser reaproveitado para
-- Compressa sem risco de um código já usado mudar de sentido.
--
-- A lista de 324 códigos (atual → novo) abaixo foi GERADA a partir do
-- catálogo real, não escrita à mão — mesma prática das migrações de
-- nomenclatura de NF (20260804000300/400): reescrever a regra em SQL criaria
-- uma segunda cópia que poderia divergir da primeira. Aqui foi um passo além:
-- o SQL inteiro, inclusive esta lista repetida duas vezes no arquivo, saiu de
-- um único script — nada foi retranscrito à mão.
--
-- Efeito verificado antes de aplicar: os 324 códigos novos são todos
-- distintos entre si e nenhum coincide com um código atual de outro produto —
-- não há risco de uma atualização em massa colidir consigo mesma.

